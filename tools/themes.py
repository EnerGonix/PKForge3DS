#!/usr/bin/env python3
"""Packs the Android PKForge's colour themes (src/PKForge.Chrome/ColorThemes.g.cs) into source/themes.inc for
the 3DS port: one row per theme, the colours the port's gfx::T palette has, in its order.
Usage: themes.py <PKForge source tree> <out file>"""
import os
import re
import sys

# The port's names, and the original's when they differ.
FIELDS = ['Void', 'Deep', 'Deck', 'Grid', 'Blue', 'Cyan', 'Ink', 'InkSoft', 'Bright', 'Well', 'WellEdge', 'Frame',
          'FrameEdge', 'BannerTop', 'BannerBottom', 'PoolLight', ('WallMid', 'WallpaperMid'),
          ('WallLight', 'WallpaperLight'), 'Label', 'Value', 'Rim', 'RimFill', 'SubInk', 'ChipInk', 'ChipTop',
          'ChipBottom', 'Band', 'ToolFill', 'ToolEdge', 'PanelFill', 'LabelColumn', 'LabelInk', 'ValueInk', 'CardFill',
          'CardRow', 'SpeciesFill', 'SpeciesEdge', 'SpeciesInk', 'NameFrame', 'Shadow', 'TabTop', 'TabBottom',
          'TabActiveTop', 'TabActiveBottom', 'PartyRim', 'PartyRimDark', 'PartyBody', 'PartyBand', 'PartySelected',
          'PartySelectedBand']


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(os.path.join(src, 'src', 'PKForge.Chrome', 'ColorThemes.g.cs'), encoding='utf-8').read()
    blocks = re.findall(r'new ColorTheme\s*\{(.*?)\n\s*\},', text, re.S)
    rows = []
    for block in blocks:
        name = re.search(r'Name = "([^"]+)"', block).group(1)
        colours = dict((k, (int(r, 16), int(g, 16), int(b, 16))) for k, r, g, b in
                       re.findall(r'(\w+) = new SKColor\(0x(\w\w), 0x(\w\w), 0x(\w\w)\)', block))
        values = []
        for f in FIELDS:
            ours, theirs = (f, f) if isinstance(f, str) else f
            r, g, b = colours[theirs]
            values.append('rgb(0x%02X, 0x%02X, 0x%02X)' % (r, g, b))
        rows.append('    {"%s", {%s}},' % (name, ', '.join(values)))
    names = [f if isinstance(f, str) else f[0] for f in FIELDS]
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/themes.py from the Android PKForge\'s ColorThemes.g.cs (GPLv3). Do not edit.\n')
        f.write('// Colour order: ' + ' '.join(names) + '\n')
        f.write('#define THEME_FIELDS(X) ' + ' '.join('X(%s)' % n for n in names) + '\n')
        f.write('constexpr int THEME_COLOURS = %d;\n' % len(names))
        f.write('const struct { const char* name; u32 colours[THEME_COLOURS]; } THEMES[] = {\n' + '\n'.join(rows) + '\n};\n')
    print(len(rows), 'themes')


if __name__ == '__main__':
    main()
