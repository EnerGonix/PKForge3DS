"""Writes source/entralink.inc for the Entralink editor, from PKHeX (GPLv3):
- the Dream World templates that may fill the Entree Forest legally (Encounters5DR.DreamWorld_Common,
  Encounters5BW.DreamWorld_BW, Encounters5B2W2.DreamWorld_B2W2): species, form, gender (255 random), one move;
- the Pass Power names (PassPower5) and the Funfest missions with the event flags each needs (FestaBlock5).
Usage: entralink.py <PKHeX checkout> <PKForge3DS dir>"""
import os
import re
import sys

PKHEX, ROOT = sys.argv[1], sys.argv[2]
CORE = os.path.join(PKHEX, 'PKHeX.Core')


def read(*p):
    return open(os.path.join(CORE, *p), encoding='utf-8-sig').read()


def dream(text, name):
    body = re.search(r'%s\s*=\s*DreamWorldEntry\.GetArray\(\w+,\s*\[(.*?)\]\);' % name, text, re.S).group(1)
    out = []
    for m in re.finditer(r'new\(([^)]*)\)', body):
        pos, named = [], {}
        for a in [x.strip() for x in m.group(1).split(',')]:
            if ':' in a:
                k, v = a.split(':')
                named[k.strip()] = v.strip()
            else:
                pos.append(a)
        species, moves = int(pos[0]), [int(x) for x in pos[2:5]]
        form = int(named.get('Form', 0))
        gender = int(named.get('Gender', 255))
        moves = [x for x in moves if x] or [0]
        for mv in moves:  # PKHeX splits one entry per special move
            out.append((species, form, gender, mv))
    return out


common = dream(read('Legality', 'Encounters', 'Data', 'Gen5', 'Encounters5DR.cs'), 'DreamWorld_Common')
bw = dream(read('Legality', 'Encounters', 'Data', 'Gen5', 'Encounters5BW.cs'), 'DreamWorld_BW')
b2w2 = dream(read('Legality', 'Encounters', 'Data', 'Gen5', 'Encounters5B2W2.cs'), 'DreamWorld_B2W2')

pp = read('Saves', 'Substructures', 'Gen5', 'PassPower5.cs')
powers = [(int(v), n) for n, v in re.findall(r'^\s*(\w+)\s*=\s*(\d+),', pp, re.M)]

festa = read('Saves', 'Substructures', 'Gen5', 'FestaBlock5.cs')
flags = re.search(r'FunfestMissionUnlockFlagRequired\s*=\s*\[(.*?)\n\s*\];', festa, re.S).group(1)
flags = re.sub(r'//[^\n]*', '', flags)
missions_flags = [[int(x) for x in re.findall(r'\d+', a)] for a in re.findall(r'\[([^\]]*)\]', flags)]
names = re.findall(r'^\s*(\w+)\s*=\s*(\d+),?', festa.split('enum Funfest5Mission')[1], re.M)
mission_names = {int(v): n for n, v in names}
max_index = max(mission_names)


def pretty(name):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', name)


def rows(entries):
    return ',\n'.join('    {%d, %d, %d, %d}' % e for e in entries)


out = ['// Generated by tools/entralink.py from PKHeX (GPLv3). Do not edit.',
       'struct DreamEntry { u16 species; u8 form; u8 gender; u16 move; };',
       'static const DreamEntry dreamCommon[] = {', rows(common), '};',
       'static const DreamEntry dreamBW[] = {', rows(bw), '};',
       'static const DreamEntry dreamB2W2[] = {', rows(b2w2), '};',
       'struct PassPowerName { u8 value; const char* name; };',
       'static const PassPowerName passPowers[] = {',
       ',\n'.join('    {%d, "%s"}' % (v, pretty(n)) for v, n in powers), '};',
       'struct FunfestMission { const char* name; u16 flags[2]; };',
       'static const FunfestMission funfestMissions[] = {',
       ',\n'.join('    {"%s", {%s}}' % (pretty(mission_names.get(i, 'Mission %d' % i)),
                                        ', '.join(str(f) for f in (missions_flags[i] + [0, 0])[:2]))
                  for i in range(max_index + 1)), '};', '']
open(os.path.join(ROOT, 'source', 'entralink.inc'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(common), len(bw), len(b2w2), len(powers), max_index + 1, len(missions_flags))
