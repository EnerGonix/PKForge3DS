"""Writes source/vivillon.inc: the Vivillon pattern of every 3DS country/region, from PKHeX (GPLv3)
PKHeX.Core/Legality/Restrictions/Locale/Vivillon3DS.cs (SameCountry, DiffCountryRegion, DiffForm; data by
abcboy101, https://github.com/abcboy101/vivillon).
Usage: vivillon.py <PKHeX checkout> <PKForge3DS dir>"""
import os
import re
import sys

PKHEX, ROOT = sys.argv[1], sys.argv[2]
text = open(os.path.join(PKHEX, 'PKHeX.Core', 'Legality', 'Restrictions', 'Locale', 'Vivillon3DS.cs'),
            encoding='utf-8').read()


def array(name):
    body = re.search(r'%s\s*=>\s*\[(.*?)\];' % name, text, re.S).group(1)
    body = re.sub(r'//[^\n]*', '', body)
    return [x.strip() for x in body.split(',') if x.strip()]


same = ['0' if x == 'XX' else str(int(x)) for x in array('SameCountry')]
diff = array('DiffCountryRegion')
forms = [str(int(x)) for x in array('DiffForm')]
assert len(diff) == len(forms), (len(diff), len(forms))


def lines(values, per=16):
    return ',\n'.join('    ' + ', '.join(values[i:i + per]) for i in range(0, len(values), per))


out = ['// Generated by tools/vivillon.py from PKHeX (GPLv3) Vivillon3DS.cs; data by abcboy101. Do not edit.',
       '// Vivillon pattern for a country with one pattern (0 = it depends on the region).',
       'static const u8 vivillonSameCountry[] = {', lines(same), '};',
       '// (country << 8 | region), sorted, and the pattern of each.',
       'static const u16 vivillonDiffRegion[] = {', lines(diff), '};',
       'static const u8 vivillonDiffForm[] = {', lines(forms), '};', '']
open(os.path.join(ROOT, 'source', 'vivillon.inc'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(same), len(diff))
