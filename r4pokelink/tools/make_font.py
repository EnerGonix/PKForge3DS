#!/usr/bin/env python3
"""Turns the NDS12 bcfnt PKForge 3DS builds (mkbcfnt -s 8) into a 1-bit C font for R4 Link.

Usage: make_font.py <nds12.bcfnt> <out font.h>
Covers printable ASCII and the Latin-1 letters Pokémon names use.
"""
import struct
import sys


def main():
    data = open(sys.argv[1], 'rb').read()
    finf = 0x14
    tglp, cwdh, cmap = struct.unpack_from('<III', data, finf + 16)
    alter = struct.unpack_from('<H', data, finf + 10)[0]
    t = tglp - 8
    cell_w, cell_h, baseline, _ = struct.unpack_from('<BBBB', data, t + 8)
    sheet_size, n_sheets, fmt, n_rows, n_lines, sheet_w, sheet_h = struct.unpack_from('<IHHHHHH', data, t + 12)
    sheet_off = struct.unpack_from('<I', data, t + 28)[0]
    assert fmt == 11, 'expected A4 sheets'

    # Code point -> glyph index from every CMAP block.
    glyph_of = {}
    off = cmap
    while off:
        b = off - 8
        begin, end, method = struct.unpack_from('<HHH', data, b + 8)
        nxt = struct.unpack_from('<I', data, b + 16)[0]
        body = b + 20
        if method == 0:
            first = struct.unpack_from('<H', data, body)[0]
            for c in range(begin, end + 1):
                glyph_of[c] = first + c - begin
        elif method == 1:
            for i, c in enumerate(range(begin, end + 1)):
                g = struct.unpack_from('<H', data, body + 2 * i)[0]
                if g != 0xFFFF:
                    glyph_of[c] = g
        else:
            count = struct.unpack_from('<H', data, body)[0]
            for i in range(count):
                c, g = struct.unpack_from('<HH', data, body + 2 + 4 * i)
                glyph_of[c] = g
        off = nxt

    # Glyph index -> (left, glyph width, advance) from every CWDH block.
    widths = {}
    off = cwdh
    while off:
        b = off - 8
        start, end, nxt = struct.unpack_from('<HHI', data, b + 8)
        for i in range(end - start + 1):
            widths[start + i] = struct.unpack_from('<bBB', data, b + 16 + 3 * i)
        off = nxt

    def morton(x, y):
        m = 0
        for i in range(3):
            m |= ((x >> i) & 1) << (2 * i) | ((y >> i) & 1) << (2 * i + 1)
        return m

    def pixel(sheet, x, y):
        tile = ((y // 8) * (sheet_w // 8) + x // 8) * 64 + morton(x % 8, y % 8)
        byte = data[sheet_off + sheet * sheet_size + tile // 2]
        return (byte >> 4) if tile & 1 else (byte & 15)

    per_sheet = n_rows * n_lines
    codes = list(range(0x20, 0x7F)) + [0xE9, 0xC9, 0xE1, 0xE0, 0xE3, 0xE7, 0xF3, 0xF5, 0xED, 0xFA, 0xEA]
    out = ['// Generated by tools/make_font.py from NDS12 (Caveras, CC BY-NC-SA 3.0): 1-bit DS-size glyphs.',
           '#pragma once', '#include <nds/ndstypes.h>', '',
           f'#define FONT_HEIGHT {cell_h}', f'#define FONT_BASELINE {baseline}', '',
           'typedef struct { u16 code; s8 left; u8 advance; u16 rows[%d]; } FontGlyph;' % cell_h, '',
           'static const FontGlyph fontGlyphs[] = {']
    for code in codes:
        g = glyph_of.get(code, alter)
        left, gw, adv = widths.get(g, (0, 0, cell_w // 2))
        sheet, index = divmod(g, per_sheet)
        gx = (index % n_rows) * (cell_w + 1)
        gy = (index // n_rows) * (cell_h + 1)
        rows = []
        for y in range(cell_h):
            bits = 0
            for x in range(min(gw, 16)):
                if pixel(sheet, gx + x, gy + y) >= 8:
                    bits |= 1 << x
            rows.append(bits)
        out.append('    {0x%04X, %d, %d, {%s}},' % (code, left, adv, ','.join('0x%04X' % r for r in rows)))
    out.append('};')
    out.append('#define FONT_GLYPHS (sizeof(fontGlyphs) / sizeof(fontGlyphs[0]))')
    open(sys.argv[2], 'w', newline='\n').write('\n'.join(out) + '\n')
    print(f'{len(codes)} glyphs, cell {cell_w}x{cell_h}, baseline {baseline}')


if __name__ == '__main__':
    main()
